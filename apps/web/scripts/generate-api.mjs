import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, rmSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import path from 'node:path';
import openapiTS, { astToString } from 'openapi-typescript';
import { writeFile } from 'node:fs/promises';

const root = fileURLToPath(new URL('../../../', import.meta.url));
const api = path.join(root, 'apps/api');
const python = process.env.RENER_PYTHON ?? path.join(api, '.venv', process.platform === 'win32' ? 'Scripts/python.exe' : 'bin/python');
if (!existsSync(python)) throw new Error('Create apps/api/.venv and install .[dev] first, or set RENER_PYTHON.');
mkdirSync(path.join(root, '.tmp'), { recursive: true });
const schema = path.join(root, '.tmp/web-openapi.json');
const result = spawnSync(python, ['-m', 'app.export_openapi', schema], { cwd: api, stdio: 'inherit' });
if (result.status !== 0) process.exit(result.status ?? 1);
const ast = await openapiTS(pathToFileURL(schema), { defaultNonNullable: false });
await writeFile(new URL('../src/lib/api/generated.ts', import.meta.url), '/** Generated by npm run generate:api. Do not edit. */\n' + astToString(ast));
rmSync(schema);
console.log('Generated src/lib/api/generated.ts from FastAPI (no running server required).');
